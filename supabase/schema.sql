-- Apenas categorias manuais podem receber associacoes manuais.
create or replace function public.validar_categoria_manual()
returns trigger
language plpgsql
set search_path = ''
as $$
declare
  categoria_tipo text;
begin
  select c.tipo into categoria_tipo
  from public.categorias as c
  where c.id = new.categoria_id;

  if categoria_tipo is distinct from 'manual' then
    raise exception 'Somente categorias do tipo manual podem receber associacoes manuais.';
  end if;

  return new;
end;
$$;

revoke all on function public.validar_categoria_manual() from public, anon, authenticated;
drop trigger if exists musica_categorias_validar_manual on public.musica_categorias;
create trigger musica_categorias_validar_manual
before insert or update on public.musica_categorias
for each row execute function public.validar_categoria_manual();

-- Autorizacao administrativa verificada no banco, nao apenas na interface.
create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.admin_users as au
    where au.user_id = (select auth.uid())
      and au.is_active = true
  );
$$;

revoke all on function public.is_admin() from public, anon, authenticated;
grant execute on function public.is_admin() to authenticated;

grant usage on schema public to anon, authenticated;
grant select on public.musicas, public.categorias, public.musica_categorias, public.dificuldades to anon, authenticated;
grant insert, update, delete on public.musicas, public.categorias, public.musica_categorias, public.dificuldades to authenticated;
-- Necessario para que o administrador possa inserir musicas sem informar um ID manualmente.
grant usage, select on all sequences in schema public to authenticated;
grant select on public.admin_users to authenticated;

alter table public.musicas enable row level security;
alter table public.categorias enable row level security;
alter table public.musica_categorias enable row level security;
alter table public.dificuldades enable row level security;
alter table public.admin_users enable row level security;

drop policy if exists musicas_read_active on public.musicas;
create policy musicas_read_active on public.musicas
for select to anon, authenticated using (ativa = true);
drop policy if exists musicas_admin_manage on public.musicas;
create policy musicas_admin_manage on public.musicas
for all to authenticated using (public.is_admin()) with check (public.is_admin());

drop policy if exists categorias_read_active on public.categorias;
create policy categorias_read_active on public.categorias
for select to anon, authenticated using (ativa = true);
drop policy if exists categorias_admin_manage on public.categorias;
create policy categorias_admin_manage on public.categorias
for all to authenticated using (public.is_admin()) with check (public.is_admin());

drop policy if exists musica_categorias_read_active on public.musica_categorias;
create policy musica_categorias_read_active on public.musica_categorias
for select to anon, authenticated using (
  exists (
    select 1 from public.musicas as m
    where m.id = musica_categorias.musica_id and m.ativa = true
  )
  and exists (
    select 1 from public.categorias as c
    where c.id = musica_categorias.categoria_id and c.ativa = true
  )
);
drop policy if exists musica_categorias_admin_manage on public.musica_categorias;
create policy musica_categorias_admin_manage on public.musica_categorias
for all to authenticated using (public.is_admin()) with check (public.is_admin());

drop policy if exists dificuldades_read_active on public.dificuldades;
create policy dificuldades_read_active on public.dificuldades
for select to anon, authenticated using (ativa = true);
drop policy if exists dificuldades_admin_manage on public.dificuldades;
create policy dificuldades_admin_manage on public.dificuldades
for all to authenticated using (public.is_admin()) with check (public.is_admin());

drop policy if exists admin_users_read_self_or_admin on public.admin_users;
create policy admin_users_read_self_or_admin on public.admin_users
for select to authenticated using (user_id = (select auth.uid()) or public.is_admin());

commit;

