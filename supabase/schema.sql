begin;

create table if not exists public.musicas (
  id bigint generated by default as identity primary key,
  codigo text not null unique check (codigo ~ '^[0-9]{3,}$'),
  nome text not null check (length(trim(nome)) > 0),
  artista text not null check (length(trim(artista)) > 0),
  ano integer null check (ano is null or ano between 1900 and 2100),
  audio_key text not null check (length(trim(audio_key)) > 0),
  ativa boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.categorias (
  id uuid primary key default gen_random_uuid(),
  slug text not null unique check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
  nome text not null check (length(trim(nome)) > 0),
  tipo text not null check (tipo in ('manual', 'faixa_ano', 'todas')),
  ano_inicio integer null,
  ano_fim integer null,
  ativa boolean not null default true,
  ordem integer not null default 100,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint categorias_regra_coerente check (
    (tipo = 'manual' and ano_inicio is null and ano_fim is null)
    or (tipo = 'faixa_ano' and ano_inicio is not null and ano_fim is not null and ano_inicio <= ano_fim)
    or (tipo = 'todas' and ano_inicio is null and ano_fim is null)
  )
);

create table if not exists public.musica_categorias (
  musica_id bigint not null references public.musicas(id) on delete cascade,
  categoria_id uuid not null references public.categorias(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (musica_id, categoria_id)
);

create table if not exists public.dificuldades (
  slug text primary key check (slug in ('facil', 'medio', 'dificil')),
  nome text not null,
  duracao_segundos integer not null check (duracao_segundos between 1 and 600),
  ativa boolean not null default true,
  ordem integer not null default 100,
  updated_at timestamptz not null default now()
);

create table if not exists public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade,
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

-- No maximo uma conta administrativa ativa por vez.
create unique index if not exists admin_users_only_one_active
  on public.admin_users ((is_active)) where is_active = true;

create index if not exists musicas_active_idx on public.musicas (ativa);
create index if not exists musicas_ano_idx on public.musicas (ano);
create index if not exists musica_categorias_categoria_idx on public.musica_categorias (categoria_id, musica_id);

create or replace function public.set_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

revoke all on function public.set_updated_at() from public, anon, authenticated;

drop trigger if exists musicas_set_updated_at on public.musicas;
create trigger musicas_set_updated_at
before update on public.musicas
for each row execute function public.set_updated_at();

drop trigger if exists categorias_set_updated_at on public.categorias;
create trigger categorias_set_updated_at
before update on public.categorias
for each row execute function public.set_updated_at();

drop trigger if exists dificuldades_set_updated_at on public.dificuldades;
create trigger dificuldades_set_updated_at
before update on public.dificuldades
for each row execute function public.set_updated_at();

